#!/usr/bin/env python3
"""agent-bootstrap session context  (Claude Code SessionStart hook).

Plain stdout from a SessionStart hook is added to the agent's context, so a
fresh agent (or one resuming after a long pause / compaction) immediately sees
the active work items, their next steps, recent activity and warnings.
"""
import json
import os
import subprocess
import sys
import time

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _abcommon as C  # noqa: E402

MAX_LOG_LINES = 8


def git(proj, *args):
    try:
        out = subprocess.run(["git", "-C", proj] + list(args), capture_output=True, text=True, timeout=5)
        return out.stdout.strip() if out.returncode == 0 else ""
    except Exception:
        return ""


def recent_log_lines(proj):
    ldir = os.path.join(proj, ".agent", "log")
    if not os.path.isdir(ldir):
        return []
    days = sorted(f for f in os.listdir(ldir) if f.endswith(".md") and f[:4].isdigit())
    lines = []
    for name in reversed(days[-3:]):
        with open(os.path.join(ldir, name), "r", encoding="utf-8") as f:
            entries = [l.rstrip() for l in f if l.startswith("- ")]
        lines = [name[:-3] + " " + e[2:] for e in entries] + lines
        if len(lines) >= MAX_LOG_LINES:
            break
    return lines[-MAX_LOG_LINES:]


def vault_status(proj):
    script = os.path.join(proj, ".agent", "bin", "vault_extract.py")
    if not os.path.isfile(script):
        return None
    try:
        out = subprocess.run([sys.executable, "-E", "-s", script, "--check", "--json", "--root", proj],
                             capture_output=True, text=True, timeout=8)
        return json.loads(out.stdout) if out.returncode == 0 else None
    except Exception:
        return None


def guard_registered(proj):
    try:
        with open(os.path.join(proj, ".claude", "settings.json"), "r", encoding="utf-8") as f:
            return "agent-bootstrap/guard_secrets.py" in f.read()
    except Exception:
        return False


def main():
    data = C.read_input()
    proj = C.project_dir(data)
    if not C.is_bootstrapped(proj):
        return
    C.save_json(C.state_path(proj, data), {
        "session_id": data.get("session_id"),
        "started_at": time.time(),
        "source": data.get("source"),
    })

    out = ["## Project agent context (generated by the agent-bootstrap SessionStart hook)"]
    branch = git(proj, "rev-parse", "--abbrev-ref", "HEAD")
    dirty = [l for l in git(proj, "status", "--porcelain").splitlines() if l.strip()]
    if branch:
        out.append("Git branch: %s; uncommitted paths: %d." % (branch, len(dirty)))

    active = C.active_work_items(proj)
    if active:
        out.append("Active work items (.agent/work):")
        for w in active:
            out.append("- %s [%s] %s | branch: %s | next-step: %s" % (
                w.get("id", "?"), w.get("status", "?"), w.get("title", w["_file"]),
                w.get("branch", "-"), w.get("next-step", "(not recorded)")))
    else:
        out.append("No active work items. New work starts with .agent/bin/new-work-item.sh \"<title>\".")

    warn_path = os.path.join(proj, ".agent", "state", "handoff-warning.json")
    warn = C.load_json(warn_path)
    if warn:
        out.append("Warning: the previous session (%s) changed code without updating its work item. "
                   "Files changed: %s." % (warn.get("session", "?"), ", ".join(warn.get("files", [])[:8])))
        try:
            os.remove(warn_path)
        except OSError:
            pass

    logs = recent_log_lines(proj)
    if logs:
        out.append("Recent activity (.agent/log):")
        out.extend("  " + l for l in logs)

    vs = vault_status(proj)
    if vs:
        out.append("Project map: .vault/_map.md (%d module notes; %d stale, %d without a purpose summary)." % (
            vs.get("modules", 0), vs.get("stale", 0), vs.get("unfilled", 0)))
    if not guard_registered(proj):
        out.append("Warning: the agent-bootstrap secret guard is not registered in .claude/settings.json.")
    out.append("Secrets are available only through .agent/bin/run-with-secrets.sh -- <command>; "
               "the user approves each use.")
    text = "\n".join(out)
    print(text[:9500])


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        sys.stderr.write("agent-bootstrap session-start hook: %r\n" % (exc,))
        sys.exit(0)
