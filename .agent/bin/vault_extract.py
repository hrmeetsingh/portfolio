# ----------------------------------------------------------------- files --
def git_files(root):
    try:
        out = subprocess.run(["git", "-C", root, "ls-files", "-co", "--exclude-standard", "-z"],
                             capture_output=True, timeout=60)
        if out.returncode != 0:
            return None
        return [p for p in out.stdout.decode("utf-8", "replace").split("\0") if p]
    except Exception:
        return None


def walk_files(root):
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
        for name in filenames:
            found.append(os.path.relpath(os.path.join(dirpath, name), root))
    return found


def blob_ids(root):
    ids = {}
    try:
        out = subprocess.run(["git", "-C", root, "ls-files", "-s", "-z"], capture_output=True, timeout=60)
        for rec in out.stdout.decode("utf-8", "replace").split("\0"):
            if "\t" in rec:
                meta, path = rec.split("\t", 1)
                parts = meta.split()
                if len(parts) >= 2:
                    ids[path] = parts[1]
    except Exception:
        pass
    return ids


def language(path):
    base = os.path.basename(path)
    if base in SPECIAL_NAMES:
        return SPECIAL_NAMES[base]
    return LANG_BY_EXT.get(os.path.splitext(base)[1])


def collect(root):
    files = git_files(root)
    if files is None:
        files = walk_files(root)
    keep = []
    for rel in files:
        rel = rel.replace("\\", "/")
        parts = rel.split("/")
        if any(p in SKIP_DIRS for p in parts[:-1]) or parts[-1] in SKIP_FILES:
            continue
        if parts[0] in (".vault", ".agent", ".claude"):
            continue
        lang = language(rel)
        full = os.path.join(root, rel)
        if not lang or not os.path.isfile(full):
            continue
        keep.append((rel, lang))
    return keep


# --------------------------------------------------------------- modules --
def group_modules(files, max_modules):
    dirs = set()
    for rel, _ in files:
        dirs.add(os.path.dirname(rel) or ".")
    def depth(d):
        return 0 if d == "." else d.count("/") + 1
    while len(dirs) > max_modules:
        deepest = max(depth(d) for d in dirs)
        if deepest == 0:
            break
        dirs = {(os.path.dirname(d) or ".") if depth(d) == deepest else d for d in dirs}
    assign = {}
    for rel, _ in files:
        d = os.path.dirname(rel) or "."
        while d not in dirs and d != ".":
            d = os.path.dirname(d) or "."
        assign[rel] = d
    return sorted(dirs), assign


def slug(key):
    if key == ".":
        return "root"
    s = re.sub(r"[^A-Za-z0-9]+", "-", key).strip("-").lower()
    return s or "module"


def read_text(path):
    try:
        if os.path.getsize(path) > MAX_FILE_BYTES:
            return ""
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            return f.read()
    except Exception:
        return ""


def scan_file(root, rel, lang):
    text = read_text(os.path.join(root, rel))
    lines = text.count("\n") + (1 if text and not text.endswith("\n") else 0)
    syms, imps = [], []
    for rx in SYMBOLS.get(lang, []):
        for m in rx.finditer(text):
            name = next((g for g in m.groups() if g), None)
            if name and not name.startswith("_") and name not in ("if", "for", "while", "switch", "return"):
                line_no = text.count("\n", 0, m.start()) + 1
                syms.append((line_no, name))
    for rx in IMPORTS.get(lang, []):
        for m in rx.finditer(text):
            imps.append(m.group(1))
    syms.sort()
    return {"lines": lines, "symbols": syms, "imports": imps}


def go_module_prefix(root):
    path = os.path.join(root, "go.mod")
    text = read_text(path) if os.path.isfile(path) else ""
    m = re.search(r"^module\s+(\S+)", text, re.M)
    return m.group(1) if m else None


def resolve(imp, rel, lang, modules, assign, file_index, go_prefix):
    """Map an import string to a module key (or None)."""
    here = os.path.dirname(rel)
    cand = None
    if lang == "python" and imp.startswith("."):
        dots = len(imp) - len(imp.lstrip("."))
        base = here
        for _ in range(dots - 1):
            base = os.path.dirname(base)
        cand = os.path.normpath(os.path.join(base, imp.lstrip(".").replace(".", "/")))
    elif imp.startswith("./") or imp.startswith("../"):
        cand = os.path.normpath(os.path.join(here, imp))
    elif lang == "rust" and (imp.startswith("super::") or imp.startswith("self::")):
        cand = os.path.normpath(os.path.join(here, imp.replace("super::", "../").replace("self::", "").replace("::", "/")))
    elif lang in ("c", "cpp", "objc", "ruby", "shell") and "/" in imp:
        cand = os.path.normpath(os.path.join(here, imp))
        if not (os.path.splitext(cand)[0] in file_index or cand in assign):
            cand = None
    if cand:
        cand = cand.replace("\\", "/")
        if cand in assign:
            return assign[cand]
        stem = os.path.splitext(cand)[0]
        if stem in file_index:
            return file_index[stem]
        d = cand
        while d and d != ".":
            if d in modules:
                return d
            d = os.path.dirname(d)
        return None
    s = imp
    if go_prefix and s.startswith(go_prefix + "/"):
        s = s[len(go_prefix) + 1:]
    s = re.sub(r"^(@/|~/|#/|crate::|package:[\w-]+/)", "", s)
    s = s.replace("::", "/").replace("\\", "/")
    if "/" not in s and lang in ("python", "java", "kotlin", "scala", "csharp", "elixir", "rust"):
        s = s.replace(".", "/")
    segs = [x for x in s.split("/") if x and x not in (".",)]
    for k in range(len(segs), 0, -1):
        tail = "/".join(segs[:k])
        if tail in file_index:
            return file_index[tail]
        for m in modules:
            if m == tail or m.endswith("/" + tail):
                return m
        if k <= 1:
            break
    return None


def module_hash(keys, blobs, root):
    h = hashlib.sha1()
    for rel in sorted(keys):
        ident = blobs.get(rel)
        if not ident:
            try:
                st = os.stat(os.path.join(root, rel))
                ident = "%d-%d" % (st.st_size, int(st.st_mtime))
            except OSError:
                ident = "missing"
        h.update(("%s:%s\n" % (rel, ident)).encode())
    return h.hexdigest()[:12]


def analyse(root, max_modules):
    files = collect(root)
    modules, assign = group_modules(files, max_modules)
    blobs = blob_ids(root)
    file_index = {}
    for rel, _ in files:
        file_index.setdefault(os.path.splitext(rel)[0], assign[rel])
    go_prefix = go_module_prefix(root)
    info = {m: {"files": [], "langs": {}, "deps": set(), "used_by": set(), "symbols": [], "entry": []} for m in modules}
    for rel, lang in files:
        m = assign[rel]
        res = scan_file(root, rel, lang)
        mod = info[m]
        mod["files"].append({"path": rel, "lang": lang, "lines": res["lines"],
                             "symbols": [s for _, s in res["symbols"][:6]]})
        mod["langs"][lang] = mod["langs"].get(lang, 0) + res["lines"]
        for line_no, name in res["symbols"]:
            mod["symbols"].append((rel, line_no, name))
        if ENTRY_RE.search(rel):
            mod["entry"].append(rel)
        for imp in res["imports"]:
            target = resolve(imp, rel, lang, modules, assign, file_index, go_prefix)
            if target and target != m:
                mod["deps"].add(target)
    for m, mod in info.items():
        for d in mod["deps"]:
            info[d]["used_by"].add(m)
        mod["hash"] = module_hash([f["path"] for f in mod["files"]], blobs, root)
        code = {k: v for k, v in mod["langs"].items() if k in CODE_LANGS}
        pick = code or mod["langs"]
        mod["language"] = max(pick, key=pick.get) if pick else "unknown"
    return info


# ----------------------------------------------------------------- notes --
def split_note(text):
    """Return (frontmatter_dict_lines, manual_before, manual_after)."""
    body = text
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end != -1:
            body = text[end + 5:]
    if AUTO_START in body and AUTO_END in body:
        before, rest = body.split(AUTO_START, 1)
        after = rest.split(AUTO_END, 1)[1]
        return before, after
    return None, None


def wl(slugs, key):
    return "[[%s]]" % slugs[key]


def render_note(key, mod, slugs, today, previous):
    deps = sorted(mod["deps"])
    used = sorted(mod["used_by"])
    fm = ["---", "type: module", "path: \"%s\"" % key, "language: %s" % mod["language"],
          "files: %d" % len(mod["files"]), "source_hash: %s" % mod["hash"], "generated: %s" % today,
          "tags: [module, lang/%s]" % mod["language"]]
    fm.append("depends_on: [%s]" % ", ".join('"%s"' % wl(slugs, d) for d in deps))
    fm.append("used_by: [%s]" % ", ".join('"%s"' % wl(slugs, u) for u in used))
    fm.append("---")
    auto = [AUTO_START,
            "**Path:** `%s` | **Language:** %s | **Files:** %d" % (key, mod["language"], len(mod["files"])),
            "",
            "**Depends on:** " + (" · ".join(wl(slugs, d) for d in deps) or "none detected"),
            "**Used by:** " + (" · ".join(wl(slugs, u) for u in used) or "none detected"),
            ""]
    if mod["entry"]:
        auto.append("**Entry points:** " + ", ".join("`%s`" % e for e in mod["entry"]))
        auto.append("")
    auto.append("### Files")
    auto.append("| File | Lines | Key symbols |")
    auto.append("|---|---:|---|")
    for f in sorted(mod["files"], key=lambda x: x["path"])[:60]:
        syms = ", ".join("`%s`" % s for s in f["symbols"]) or ""
        auto.append("| `%s` | %d | %s |" % (os.path.relpath(f["path"], key) if key != "." else f["path"], f["lines"], syms))
    if len(mod["files"]) > 60:
        auto.append("| ... %d more files | | |" % (len(mod["files"]) - 60))
    if mod["symbols"]:
        auto.append("")
        auto.append("### Symbols (first %d)" % MAX_SYMBOLS)
        for rel, line_no, name in mod["symbols"][:MAX_SYMBOLS]:
            auto.append("- `%s` - %s:%d" % (name, rel, line_no))
    auto.append(AUTO_END)

    if previous:
        before, after = split_note(previous)
    else:
        before, after = None, None
    if before is None:
        before = "\n# %s\n\n" % (key if key != "." else "(project root)")
        after = ("\n\n## Purpose\n%s: 2-4 sentences on what this module is for, its main responsibilities "
                 "and how it fits the system -->\n\n## Key concepts\n\n## Gotchas\n\n## Notes\n" % FILL_MARK)
    return "\n".join(fm) + "\n" + before + "\n".join(auto) + after


def purpose_line(text):
    m = re.search(r"## Purpose\n(.*?)(\n## |\Z)", text, re.S)
    if not m:
        return ""
    body = m.group(1).strip()
    if not body or FILL_MARK in body:
        return ""
    first = body.splitlines()[0].strip()
    return (first[:117] + "...") if len(first) > 120 else first


def render_map(root, info, slugs, notes_text, today):
    name = os.path.basename(os.path.abspath(root))
    entries = sorted({e for mod in info.values() for e in mod["entry"]})
    langs = {}
    for mod in info.values():
        for k, v in mod["langs"].items():
            if k in CODE_LANGS:
                langs[k] = langs.get(k, 0) + v
    top = ", ".join("%s (%d lines)" % (k, v) for k, v in sorted(langs.items(), key=lambda x: -x[1])[:6])
    lines = ["---", "type: map", "generated: %s" % today, "tags: [map]", "---",
             "# %s - project map" % name, "",
             "This vault is generated by `.agent/bin/vault_extract.py` and curated by agents. Start here, "
             "follow links to module notes, then open the source files they cite.", "",
             "**Languages:** %s" % (top or "unknown"), "",
             "**Entry points:** " + (", ".join("`%s`" % e for e in entries[:20]) or "none detected"), "",
             "## Modules", "", "| Module | Language | Files | Depends on | Purpose |", "|---|---|---:|---|---|"]
    for key in sorted(info):
        mod = info[key]
        deps = " ".join(wl(slugs, d) for d in sorted(mod["deps"])[:6])
        lines.append("| %s | %s | %d | %s | %s |" % (wl(slugs, key), mod["language"], len(mod["files"]),
                                                    deps, purpose_line(notes_text.get(key, "")) or "-"))
    lines += ["", "## Conventions", "",
              "- Module notes live in `modules/`. Regenerated content sits between the `vault:auto` markers.",
              "- Agents fill `## Purpose`, `## Key concepts` and `## Gotchas`; those sections survive regeneration.",
              "- Work items are tracked outside the vault in `.agent/work/`; history in `.agent/log/`.",
              "- Dependency edges are inferred from import statements and can be incomplete.", ""]
    return "\n".join(lines)


# ------------------------------------------------------------------ main --
def run(args):
    root = os.path.abspath(args.root)
    vault = os.path.join(root, args.vault)
    mdir = os.path.join(vault, "modules")
    index_path = os.path.join(vault, "_index.json")
    info = analyse(root, args.max_modules)
    keys = sorted(info)
    used, slugs = set(), {}
    for k in keys:
        s, n = slug(k), 2
        while s in used:
            s, n = "%s-%d" % (slug(k), n), n + 1
        used.add(s)
        slugs[k] = s
    index = {}
    if os.path.isfile(index_path):
        try:
            with open(index_path, "r", encoding="utf-8") as f:
                index = json.load(f)
        except Exception:
            index = {}
    old = index.get("modules", {})

    if args.check:
        stale = [k for k in keys if old.get(k, {}).get("hash") != info[k]["hash"]]
        unfilled, review = [], []
        for k in keys:
            note = os.path.join(mdir, slugs[k] + ".md")
            text = open(note, encoding="utf-8").read() if os.path.isfile(note) else ""
            if not text or FILL_MARK in text:
                unfilled.append(k)
            elif old.get(k, {}).get("purpose_hash") not in (None, info[k]["hash"]):
                review.append(k)
        result = {"modules": len(keys), "stale": len(stale), "unfilled": len(unfilled),
                  "needs_review": len(review), "stale_list": stale, "unfilled_list": unfilled,
                  "review_list": review, "vault_exists": os.path.isdir(vault)}
        if args.json:
            print(json.dumps(result))
        else:
            print("modules: %d | stale: %d | unfilled: %d | purpose may be outdated: %d" % (
                len(keys), len(stale), len(unfilled), len(review)))
            for label, items in (("stale", stale), ("unfilled", unfilled), ("review", review)):
                for k in items[:50]:
                    print("  %s: %s -> .vault/modules/%s.md" % (label, k, slugs[k]))
        return 0

    os.makedirs(mdir, exist_ok=True)
    today = time.strftime("%Y-%m-%d")
    notes_text, new_index = {}, {}
    for k in keys:
        path = os.path.join(mdir, slugs[k] + ".md")
        prev = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
        text = render_note(k, info[k], slugs, today, prev)
        if text != prev:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
        notes_text[k] = text
        entry = {"slug": slugs[k], "hash": info[k]["hash"]}
        filled = FILL_MARK not in text
        prev_entry = old.get(k, {})
        if filled:
            entry["purpose_hash"] = prev_entry.get("purpose_hash") or info[k]["hash"]
        new_index[k] = entry
    archived = []
    known = {slugs[k] + ".md" for k in keys}
    for name in os.listdir(mdir):
        if name.endswith(".md") and name not in known:
            os.makedirs(os.path.join(vault, "_archive"), exist_ok=True)
            shutil.move(os.path.join(mdir, name), os.path.join(vault, "_archive", name))
            archived.append(name)
    with open(os.path.join(vault, "_map.md"), "w", encoding="utf-8") as f:
        f.write(render_map(root, info, slugs, notes_text, today))
    with open(index_path, "w", encoding="utf-8") as f:
        json.dump({"generated": today, "modules": new_index}, f, indent=2, sort_keys=True)
    edges = sum(len(m["deps"]) for m in info.values())
    print("vault: %s | modules: %d | dependency edges: %d | archived notes: %d" % (
        os.path.relpath(vault, root), len(keys), edges, len(archived)))
    return 0


