#!/usr/bin/env python3
"""Generate / refresh an Obsidian vault that maps this project's structure.

Stack-agnostic: works on any repository by grouping files into modules
(directories), extracting symbols and imports with per-language regexes, and
resolving imports to other modules by path-suffix matching. It is a map for
navigation, not a compiler: treat dependency edges as hints.

  python3 .agent/bin/vault_extract.py            # create or refresh .vault/
  python3 .agent/bin/vault_extract.py --check    # report stale / unfilled notes
  python3 .agent/bin/vault_extract.py --check --json

Everything between the vault:auto markers in a note is regenerated. Anything
outside them (Purpose, Notes, your own sections) is preserved.
Standard library only; Python 3.9+.
"""
